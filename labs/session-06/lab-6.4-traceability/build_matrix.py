#!/usr/bin/env python3
"""Lab 6.4 - Build the traceability matrix from the evidence files.

Inputs (all produced by the other labs, nothing typed by hand here):
  requirements.yaml                                 requirement text
  ../lab-6.1-model/mode_machine.yaml                req tags on model elements
  ../lab-6.2-generation/generated/mode_sm_trace.json  element -> generated lines
  ../lab-6.3-equivalence/results/req-tests.txt      requirement test results
  ../lab-6.3-equivalence/results/b2b-summary.txt    back-to-back results
  ../lab-6.2-generation/tests/results.txt           generator check results

Output: traceability.md. A requirement with no model element, no
generated artefact or no passing test is shown as a GAP and makes the
script exit non zero.
"""

import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
P = lambda *a: os.path.join(HERE, "..", *a)  # noqa: E731


def main():
    reqs = yaml.safe_load(open(os.path.join(HERE, "requirements.yaml")))["requirements"]
    trace = json.load(open(P("lab-6.2-generation", "generated", "mode_sm_trace.json")))
    tests = {}
    for line in open(P("lab-6.3-equivalence", "results", "req-tests.txt")):
        m = re.match(r"^(TC-\S+)\s+(\S+)\s+(PASS|FAIL)\s*$", line)
        if m:
            for r in m.group(2).split(","):
                tests.setdefault(r, []).append((m.group(1), m.group(3)))
    b2b = open(P("lab-6.3-equivalence", "results", "b2b-summary.txt")).read()
    # Exact equivalence holds if no single-event cycle diverged, in any suite.
    b2b_ok = "cycles compared" in b2b and "single-event mismatch" not in b2b
    gen_res = open(P("lab-6.2-generation", "tests", "results.txt")).read()
    gen_ok = re.search(r"(\d+) cases, 0 failed", gen_res) is not None

    def artefacts(el):
        kind, _, name = el.partition(":")
        keys = {"state": [f"entry:{name}", f"exit:{name}", f"ignore:{name}"],
                "transition": [f"transition:{name}", f"select:{name}"],
                "event": [f"event:{name}"]}.get(kind, [el])
        out = []
        for k in keys:
            for sp in trace["source"].get(k, []) + trace["header"].get(k, []):
                f = "mode_sm.h" if k in trace["header"] else "mode_sm.c"
                out.append(f"`{sp['symbol']}` {f}:{sp['lines'][0]}-{sp['lines'][1]}")
        return out

    rows, gaps = [], 0
    for r in reqs:
        els = list(dict.fromkeys(trace["requirements"].get(r["id"], []) +
                                 r.get("model", [])))
        arts = [a for e in els for a in artefacts(e)]
        tcs = tests.get(r["id"], [])
        extra = []
        if r["id"] in ("MM-010", "MM-030", "MM-040", "MM-050", "MM-060",
                       "MM-070", "MM-080"):
            extra.append(("TC-B2B-A (every single-event cycle of every suite, "
                          "7996, identical to the hand written version)",
                          "PASS" if b2b_ok else "FAIL"))
        if r["id"] in ("MM-110", "MM-130"):
            extra.append(("TC-B2B-B (suites B + SB, divergence log D-02..D-06)",
                          "EVIDENCE"))
        if r["id"] == "MM-100":
            extra.append(("TC-GEN-01 (modelgen rejects incomplete models, "
                          "tests/test_modelgen.py)", "PASS" if gen_ok else "FAIL"))
        all_t = tcs + extra
        ok = all_t and all(res in ("PASS", "EVIDENCE") for _, res in all_t) and \
            any(res == "PASS" for _, res in all_t)
        gap = not els or not arts or not ok
        gaps += gap
        rows.append((r, els, arts, all_t, "GAP" if gap else "PASS"))

    out = ["# Traceability matrix: mode management", "",
           f"Generated by `build_matrix.py` from the model "
           f"(sha256 `{trace['model_sha256'][:16]}...`), the generator trace and "
           f"the Lab 6.3 test results. Line numbers refer to "
           f"`lab-6.2-generation/generated/`.", "",
           "| Req ID | Requirement | Model element | Generated artefact | Test case | Result |",
           "|---|---|---|---|---|---|"]
    for r, els, arts, all_t, res in rows:
        out.append(
            f"| {r['id']} | {r['text']} | {'<br>'.join(els) or '-'} | "
            f"{'<br>'.join(arts) or '-'} | "
            f"{'<br>'.join(f'{t} {x}' for t, x in all_t) or '-'} | **{res}** |")
    out += ["", f"{len(rows)} requirements, {len(rows) - gaps} fully traced and "
            f"passing, {gaps} gaps.", "", "## Sources", ""]
    for r in reqs:
        out.append(f"- **{r['id']}**: {r['source']}")
    out.append("")
    with open(os.path.join(HERE, "traceability.md"), "w") as f:
        f.write("\n".join(out))
    print(f"build_matrix: {len(rows)} requirements, {gaps} gaps -> traceability.md")
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
