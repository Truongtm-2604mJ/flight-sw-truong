#!/bin/sh
# Session 6 - target evidence: the generated mode manager on RTEMS 6 / LEON3 (SIS).
#
# Builds lab6-test.exe and lab6-flight.exe, runs the three Session 5 system
# scenarios against them under SIS, measures the MM-150 command latency, and
# writes ../lab-6.2-generation/logs/sis-summary.md. About 10 minutes.
#
#   cd labs/session-06/app
#   RTEMS_PREFIX=$HOME/Work/01.Code/rtems/rtems/6 ./run-sis.sh
#
# Environment: RTEMS_PREFIX (default: as in rtems.mk), SIS (default:
# sparc-rtems6-sis, from RTEMS_PREFIX/bin if present, else from PATH).
set -u
cd "$(dirname "$0")"

if [ -n "${RTEMS_PREFIX:-}" ] && [ -x "$RTEMS_PREFIX/bin/sparc-rtems6-sis" ]; then
    SIS=${SIS:-$RTEMS_PREFIX/bin/sparc-rtems6-sis}
else
    SIS=${SIS:-sparc-rtems6-sis}
fi
command -v "$SIS" >/dev/null 2>&1 || { echo "SIS not found: $SIS (set RTEMS_PREFIX or SIS)"; exit 2; }

G=../../session-05/lab-5.4-fault-injection/ground
L=../lab-6.2-generation/logs
mkdir -p "$L"

echo "== build"
if [ -z "${SKIP_BUILD:-}" ]; then
    make rtems ${RTEMS_PREFIX:+RTEMS_PREFIX="$RTEMS_PREFIX"} || exit 2
fi

echo "== 1/3 gs_modes (Lab 5.3 scenario), about 2 min"
python3 $G/gs_modes.py --pty --spawn "$SIS -leon3 -rt -r lab6-test.exe" \
    --log $L/sis-modes.log > /dev/null 2>&1
echo "== 2/3 check_flight (flight build), about 30 s"
python3 $G/check_flight.py --pty --spawn "$SIS -leon3 -rt -r lab6-flight.exe" \
    --log $L/sis-check-flight.log > /dev/null 2>&1
echo "== 3/3 fault campaign + 300 s false positive run, about 8 min"
python3 $G/campaign.py --pty --nv-volatile \
    --spawn "$SIS -leon3 -rt -r lab6-test.exe" --label sis-generated --fp-seconds 300 \
    --results $L/campaign-sis-generated.md --log $L/sis-campaign.log \
    > /dev/null 2>&1
echo "== MM-150 latency"
python3 ../lab-6.2-generation/latency.py $L/sis-modes.log --label sis > /dev/null 2>&1

result() { grep -h "# result:\|^Checks:" "$1" 2>/dev/null | tail -n 1; }
boot=$(grep -h -m1 "Mode manager: GENERATED" $L/sis-modes.log 2>/dev/null | sed 's/^.*console *//')
{
    echo "# Target runs: RTEMS 6 / LEON3 on SIS"
    echo
    echo "Generated by \`app/run-sis.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
    echo
    echo "- Simulator: $(grep -h -m1 -o 'SIS - SPARC.*' $L/sis-modes.log 2>/dev/null | sed 's/ *copyright.*//')"
    echo "- Compiler: $(${RTEMS_PREFIX:+$RTEMS_PREFIX/bin/}sparc-rtems6-gcc --version 2>/dev/null | head -n 1)"
    echo "- Images: \`lab6-test.exe\` (FDIR_TEST_BUILD), \`lab6-flight.exe\` (flight)"
    echo "- Boot banner: \`$boot\`"
    echo
    echo "| Scenario | Log | Result |"
    echo "|---|---|---|"
    echo "| gs_modes.py (Lab 5.3 scenario) | \`sis-modes.log\` | $(result $L/sis-modes.log) |"
    echo "| check_flight.py (flight build) | \`sis-check-flight.log\` | $(result $L/sis-check-flight.log) |"
    echo "| campaign.py, six injections + 300 s false positive run | \`sis-campaign.log\`, \`campaign-sis-generated.md\` | $(result $L/campaign-sis-generated.md) |"
    echo "| MM-150 command latency | \`latency-sis.md\` | $(grep -h -o 'Maximum [0-9.]* s' $L/latency-sis.md 2>/dev/null), $(grep -h -o 'PASS\|FAIL' $L/latency-sis.txt 2>/dev/null) |"
    echo
    echo "Failed checks:"
    echo
    grep -h "  FAIL  " $L/sis-modes.log $L/sis-check-flight.log $L/sis-campaign.log 2>/dev/null \
        | sed 's/^\[ *\([0-9.]*\)\] *FAIL */- (\1 s) /' || true
} > $L/sis-summary.md
cat $L/sis-summary.md
